"""Export a measured, 2/4 folk melody as note events, never audio PCM."""
from pathlib import Path
from fractions import Fraction
import csv, json, math, struct, zlib
from game_fingering import Note, OPEN_MIDI, assign

ROOT = Path(__file__).resolve().parent.parent
BPM = 96
# Common single-melody version, 27 complete 2/4 bars, with phrase rests.
# Rhythm checked against song 23 (PDF page 28) of the Y's Men songbook:
# https://www.ysmen.org.tw/upload/info_center/f202111031038110.pdf
# Only the traditional melody is used; no lyrics, chords or recording.
# Degree 1 = G3; move the whole melody together into the existing D3..C5 range.
BARS = [
    "3:1 3:1/2 5:1/2", "6:1/2 8:1/2 8:1/2 6:1/2", "5:1 5:1/2 6:1/2", "5:1 R:1",
    "3:1 3:1/2 5:1/2", "6:1/2 8:1/2 8:1/2 6:1/2", "5:1 5:1/2 6:1/2", "5:1 R:1",
    "5:1 5:1", "5:1 3:1/2 5:1/2", "6:1 6:1", "5:1 R:1",
    "3:1 2:1/2 3:1/2", "5:1 3:1/2 2:1/2", "1:1 1:1/2 2:1/2", "1:1 R:1",
    "3:1/2 2:1/2 1:1/2 3:1/2", "2:3/2 3:1/2", "5:1 6:1/2 8:1/2", "5:2",
    "2:1 3:1/2 5:1/2", "2:1/2 3:1/2 1:1/2 -6:1/2", "-5:2", "-6:1 1:1",
    "2:3/2 3:1/2", "1:1/2 2:1/2 1:1/2 -6:1/2", "-5:2",
]
DEGREE = {-5:50, -6:52, 1:55, 2:57, 3:59, 5:62, 6:64, 8:67}

def validate(events):
    assert 0 < len(events) <= 120  # two cycles/event plus commit fit a 256-clock audio frame
    previous = -1
    last_lane = {}
    for e in events:
        assert e['t_on_ms'] >= previous
        assert 0 < e['duration_ms'] <= 65535
        assert 50 <= e['midi_note'] <= 72 and 0 <= e['lane'] <= 3
        assert 0 < e['phase_inc'] < 1 << 26
        assert e['t_on_ms']*48 < 1 << 24 and e['duration_ms']*48 < 1 << 24
        assert e['t_on_ms']-last_lane.get(e['lane'], -100000) >= 250
        previous = e['t_on_ms']; last_lane[e['lane']] = previous

def main():
    directory = ROOT/'scores'; directory.mkdir(exist_ok=True)
    beat = Fraction(60000, BPM)
    elapsed = Fraction(0)
    events = []
    sample_times = []
    for bar in BARS:
        assert sum(Fraction(token.split(':')[1]) for token in bar.split()) == 2, ('invalid 2/4 bar',bar)
        for token in bar.split():
            degree, duration = token.split(':')
            length = beat*Fraction(duration)
            if degree == 'R':
                elapsed += length
                continue
            midi = DEGREE[int(degree)]
            events.append(dict(t_on_ms=round(elapsed), duration_ms=round(length), lane=0,
                flags=0, phase_inc=round(440*2**((midi-69)/12)*2**32/48000),
                midi_note=midi, velocity_hint=2, group_id=0))
            sample_times.append((round(elapsed*48),round(length*48)))
            elapsed += length
    fingering = assign([Note(t, d, event['midi_note'])
                        for event, (t, d) in zip(events, sample_times)])
    for event, (lane, _) in zip(events, fingering):
        event['lane'] = lane
    validate(events)
    with (directory/'jasmine.csv').open('w', newline='', encoding='utf-8') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(events[0])); writer.writeheader(); writer.writerows(events)
    payload = b''.join(struct.pack('<IHBBIBBH', *e.values()) for e in events)
    (directory/'jasmine_events.bin').write_bytes(payload)
    # Runtime ROM keeps two 24-bit sample times, exact 26-bit DDS and lane.
    # Synchronous 80-bit words; unused slots are explicitly initialized to zero.
    # Derive runtime times from rational beats, not rounded CSV milliseconds.
    words = [(e['lane']<<74) | (e['phase_inc']<<48) | (d<<24) | t
             for e,(t,d) in zip(events,sample_times)]
    (ROOT/'mem/jasmine_game.mem').write_text(''.join(f'{w:020x}\n' for w in words+[0]*(128-len(words))), encoding='ascii')
    manifest = dict(title='茉莉花', alias='JASMINE', arrangement='常见单旋律、27 小节 2/4、保留句尾休止、无伴奏',
        bpm=BPM, tonic='G3', sample_rate_hz=48000, event_bytes=16, event_count=len(events),
        time_signature='2/4',bar_count=len(BARS),runtime_time_unit='48kHz samples from rational beats',
        reference='https://www.ysmen.org.tw/upload/info_center/f202111031038110.pdf#page=28',
        duration_ms=round(elapsed), midi_min=min(DEGREE.values()), midi_max=max(DEGREE.values()),
        crc32=f'{zlib.crc32(payload):08x}',
        lane_assignment='offline: non-overlapping voices; prefer nearby notes on different strings',
        open_midi=list(OPEN_MIDI),
        fingering=[dict(event=i, lane=lane, fret=fret) for i,(lane,fret) in enumerate(fingering)],
        slots_available=5, populated_slots=1)
    (directory/'jasmine.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    (ROOT/'rtl/config/game_score_config.vh').write_text(
        '// Generated by tools/generate_jasmine_score.py; score data, not PCM.\n'
        f'`define GAME_EVENT_COUNT {len(events)}\n`define GAME_DURATION_SAMPLES {round(elapsed)*48}\n', encoding='ascii')
    print(f'JASMINE: {len(events)} events, {round(elapsed)} ms, MIDI {manifest["midi_min"]}..{manifest["midi_max"]}, CRC32 {manifest["crc32"]}')

if __name__ == '__main__':
    main()
