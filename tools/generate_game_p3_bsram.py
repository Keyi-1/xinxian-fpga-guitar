"""Writable DPB bank with exactly the accepted P2 initialization and latency."""
from pathlib import Path
import argparse
import hashlib
import re
from generate_game_p2_bsram import build, ROOT


def initial_bank():
    old=[int(x,16) for x in (ROOT/'mem/game_p2_static.mem').read_text().splitlines()]
    # User removed the original 256-event slow practice. Keep every other
    # event unchanged, including the disabled diagnostic, then reclaim space.
    words=old[:67]+old[323:959]+[0]*(2048-703)
    assert len(words)==2048
    return words,(''.join(f'{w:024x}\n' for w in words)).encode('ascii')


def writable():
    words,initial=initial_bank()
    packed=[]
    for word in words:
        value=(word&((1<<25)-1)) | (((word>>32)&((1<<25)-1))<<25) | (((word>>64)&2047)<<50) | (((word>>80)&65535)<<61)
        restored=(value&((1<<25)-1)) | (((value>>25)&((1<<25)-1))<<32) | (((value>>50)&2047)<<64) | (((value>>61)&65535)<<80)
        assert restored==word, 'Only validated canonical words can be packed'
        packed.append(value)
    lines=['// Generated by tools/generate_game_p3_bsram.py; do not hand-edit.',
           '// Canonical logical96-bit bank SHA256: '+hashlib.sha256(initial).hexdigest()]
    for page in range(2):
        for column in range(5):
            name=f'score_p{page}_b{column}';bit=column*16
            lines += [f'DPB {name} (.DOA(audio_{"low" if page==0 else "high"}[{bit}+:16]),.DOB(display_{"low" if page==0 else "high"}[{bit}+:16]),',
                f"    .DIA(16'd0),.DIB(packed_write[{bit}+:16]),.BLKSELA(3'd0),.BLKSELB(3'd0),",
                "    .ADA({audio_address[9:0],4'b0000}),.ADB({system_address[9:0],2'b00,{2{write_enable}}}),",
                f"    .WREA(1'b0),.WREB(write_enable && system_address[10]==1'b{page}),.CLKA(audio_clk),.CLKB(display_clk),",
                f"    .CEA(audio_read),.CEB(!write_enable ? display_read : system_address[10]==1'b{page}),",
                "    .OCEA(1'b0),.OCEB(1'b0),.RESETA(1'b0),.RESETB(1'b0));",
                f'defparam {name}.BIT_WIDTH_0=16;', f'defparam {name}.BIT_WIDTH_1=16;',
                f"defparam {name}.READ_MODE0=1'b0;", f"defparam {name}.READ_MODE1=1'b0;"]
            for block in range(64):
                value=sum(((packed[page*1024+block*16+k]>>bit)&65535)<<(16*k) for k in range(16))
                lines.append(f"defparam {name}.INIT_RAM_{block:02X}=256'h{value:064x};")
    return ('\n'.join(lines)+'\n').encode('ascii')


if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    outputs={ROOT/'rtl/config/game_p3_bsram_init.vh':writable(),ROOT/'mem/game_p3_initial.mem':initial_bank()[1]}
    for path,data in outputs.items():
        if args.check:assert path.read_bytes()==data, 'Stale writable DPB initializer/bank'
        else:path.write_bytes(data)
    print('PASS: logical96-bit exact records in77 physical bits, 10 DPB16 slices; 703 retained initial events, 1345 import rows, page-qualified byte writes')
