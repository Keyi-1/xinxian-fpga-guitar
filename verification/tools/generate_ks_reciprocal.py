"""Generate the parallel piecewise-linear DDS reciprocal lookup (no divider)."""
from pathlib import Path
def generate():
    lines=['// Reciprocal of normalized DDS increment: Q24/(1+i/64).', '// Generated by tools/generate_ks_reciprocal.py; convex linear interpolation.', 'function [42:0] ks_reciprocal;','input [5:0] index;','begin case(index)']
    for i in range(64):
        a=round(2**24/(1+i/64));b=round(2**24/(1+(i+1)/64))
        lines.append(f"6'd{i}: ks_reciprocal={{25'd{a},18'd{a-b}}};")
    return '\n'.join(lines+['endcase end endfunction',''])
if __name__=='__main__':
    path=Path(__file__).resolve().parents[1]/'rtl/config/ks_reciprocal.vh'
    path.write_text(generate())
