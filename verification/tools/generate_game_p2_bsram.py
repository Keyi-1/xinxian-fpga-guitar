"""Pack exact 16-bit rows for Gowin's two-clock DPB primitive, no inference.

The canonical 96-bit event bank remains the source of truth. Each 256-bit INIT
contains sixteen little-index-first 16-bit rows. Two pages x six slices retain
the full 2048-record capacity; primitive normal reads have one-clock latency.
"""
from pathlib import Path
import argparse
import hashlib

ROOT=Path(__file__).resolve().parent.parent


def build():
    bank=ROOT/'mem/game_p2_static.mem'
    words=[int(x,16) for x in bank.read_text(encoding='ascii').splitlines()]
    assert len(words)==2048 and all(0<=w<1<<96 for w in words)
    rows=['// Generated by tools/generate_game_p2_bsram.py; do not hand-edit.',
          '// Canonical 96-bit bank SHA256: '+hashlib.sha256(bank.read_bytes()).hexdigest()]
    for page in range(2):
        for column in range(6):
            instance=f'score_p{page}_b{column}'
            bus='high' if page else 'low'
            lo=column*16
            rows += [f'DPB {instance} (',f'    .DOA(audio_{bus}[{lo}+:16]),.DOB(display_{bus}[{lo}+:16]),',
                "    .DIA(16'd0),.DIB(16'd0),.BLKSELA(3'd0),.BLKSELB(3'd0),",
                "    .ADA({audio_address[9:0],4'b0000}),.ADB({display_address[9:0],4'b0000}),",
                "    .WREA(1'b0),.WREB(1'b0),.CLKA(audio_clk),.CLKB(display_clk),",
                "    .CEA(audio_read),.CEB(display_read),.OCEA(1'b0),.OCEB(1'b0),.RESETA(1'b0),.RESETB(1'b0));",
                f'defparam {instance}.BIT_WIDTH_0=16;',f'defparam {instance}.BIT_WIDTH_1=16;',
                f"defparam {instance}.READ_MODE0=1'b0;",f"defparam {instance}.READ_MODE1=1'b0;",
                f'defparam {instance}.RESET_MODE="SYNC";']
            for block in range(64):
                value=sum(((words[page*1024+block*16+i]>>lo)&65535)<<(16*i) for i in range(16))
                assert all((value>>(16*i))&65535==(words[page*1024+block*16+i]>>lo)&65535 for i in range(16))
                rows.append(f"defparam {instance}.INIT_RAM_{block:02X}=256'h{value:064x};")
    return ('\n'.join(rows)+'\n').encode('ascii')


def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    path=ROOT/'rtl/config/game_p2_bsram_init.vh';data=build()
    if a.check:assert path.read_bytes()==data,'Stale P2 BSRAM initializer'
    else:path.write_bytes(data)
    print('PASS: 2048 x 96-bit exact rows, two pages x six DPB16 slices, all initializer rows round-trip')


if __name__=='__main__':main()
