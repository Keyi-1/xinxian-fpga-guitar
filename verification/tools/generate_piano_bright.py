"""Bounded 32-mode alternate timbre, derived from the existing rock gain table."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
    gains=[int(v,16) for v in (ROOT/'mem/harmonic_gain_rock.mem').read_text().split()]
    assert len(gains)==32 and all(0<v<32768 for v in gains)
    # A nonzero ROM coefficient can still disappear after 16-bit amplitude
    # quantization. Keep even the last modes above that floor at note onset.
    normalized=[max(16,round(g*32760/sum(gains))) for g in gains]
    normalized[0]+=32760-sum(normalized)
    assert sum(normalized)<=32768
    (ROOT/'mem/piano_bright_gain.mem').write_text(''.join(f'{g:04X}\n' for g in normalized),encoding='ascii')
    # Parallel note-on loads must be constants/muxes. A multi-read memory here
    # makes Gowin duplicate tiny ROMs into dozens of physical block RAMs.
    cases=''.join(f"            5'd{i}: piano_bright_gain_for=16'h{g:04X};\n" for i,g in enumerate(normalized))
    (ROOT/'rtl/config/piano_bright_coeffs.vh').write_text(
        '// Generated by tools/generate_piano_bright.py; Q15 gain sum 32760.\n'
        'function [15:0] piano_bright_gain_for;\n'
        '    input [4:0] index;\n    begin\n        case(index)\n'+cases+
        "            default: piano_bright_gain_for=16'd0;\n"
        '        endcase\n    end\nendfunction\n',encoding='ascii')
    print('32 nonzero modal gains; Q15 sum',sum(normalized))
if __name__=='__main__':main()
